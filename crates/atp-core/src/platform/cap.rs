//! Capabilities: which shared commands a platform supports.

/// Shared operations a platform can provide. Drives `--help` (unsupported
/// commands are hidden) and the `atp platforms` matrix.
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub enum Cap {
  QrLogin,
  /// `login --token`: an access token or API credentials instead of cookies.
  TokenLogin,
  Search,
  SearchUsers,
  SearchTopics,
  Hot,
  Feed,
  Read,
  Comments,
  Replies,
  Likers,
  Reposts,
  User,
  UserPosts,
  Followers,
  Following,
  Collections,
  Favorites,
  Likes,
  History,
  Notifications,
  Unread,
  Like,
  Favorite,
  Comment,
  /// `comment --image`.
  CommentImages,
  DeleteComment,
  Follow,
  Publish,
  Delete,
  Download,
  AccountInsights,
  PostInsights,
  /// Chat platforms: conversations, their messages and live events.
  Chats,
  Messages,
  Send,
  Members,
  React,
  Edit,
  Listen,
}

