/// Whether a WGS-84 point is in mainland China.
pub fn mainland(lng: f64, lat: f64) -> bool {
  let row = ((lat - LAT0) / STEP).floor();
  let col = ((lng - LNG0) / STEP).floor();
  if row < 0.0 || col < 0.0 || col > 255.0 {
    return false;
  }
  let Some(ranges) = ROWS.get(row as usize) else {
    return false;
  };
  let col = col as u8;
  let in_grid = ranges.chunks(2).any(|r| r[0] <= col && col < r[1]);
  in_grid && !inside(lng, lat, HONG_KONG) && !inside(lng, lat, MACAO)
}

/// Even-odd point-in-polygon test.
fn inside(x: f64, y: f64, ring: &[(f64, f64)]) -> bool {
  let mut c = false;
  let mut j = ring.len() - 1;
  for (i, &(x1, y1)) in ring.iter().enumerate() {
    let (x2, y2) = ring[j];
    if (y1 > y) != (y2 > y) && x < (x2 - x1) * (y - y1) / (y2 - y1) + x1 {
      c = !c;
    }
    j = i;
  }
  c
}
